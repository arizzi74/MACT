#!/usr/bin/env node
// Rebuild the fully offline renderer from package-lock.json-pinned packages.
// npm ci --ignore-scripts && npm run build:mermaid [-- --check]
import {build, version as esbuildVersion} from 'esbuild';
import {readFile, writeFile, readdir, access} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const output = 'internal/admin/static/webui-mermaid-runtime.js';
const noticeOutput = 'internal/admin/static/webui-mermaid-LICENSE.txt';
const inventoryOutput = 'internal/admin/static/webui-mermaid-dependencies.json';
const check = process.argv.includes('--check');
if (process.argv.slice(2).some(arg => arg !== '--check')) throw new Error('Usage: node scripts/build-mermaid.mjs [--check]');
const json = async file => JSON.parse(await readFile(path.join(root, file), 'utf8'));
const mermaidPackage = await json('node_modules/mermaid/package.json');
const packageConfig = await json('package.json');
if (packageConfig.devDependencies.mermaid !== mermaidPackage.version || packageConfig.devDependencies.esbuild !== esbuildVersion) throw new Error('Install the pinned dependencies with npm ci first.');
// Mermaid 12.2.0 publishes js-yaml 4.3.0 inside this dedicated chunk, outside
// npm's dependency graph. Replace its two exports with the patched compatible
// package. A reviewed hash prevents silently replacing a changed upstream chunk
// or accidentally dropping unrelated code during a future Mermaid update.
const yamlChunk = path.join(root, 'node_modules/mermaid/dist/chunks/mermaid.core/chunk-LNGE3PJU.mjs');
const yamlChunkHash = '2cb4e5f8d5fd99daccb0135fda6a5583c91f39efb0bb845af9d968ed427efcb2';
if (mermaidPackage.version !== '12.2.0' || createHash('sha256').update(await readFile(yamlChunk)).digest('hex') !== yamlChunkHash) throw new Error('Review the Mermaid prebundled YAML replacement before rebuilding this version.');
const yamlPackage = await json('node_modules/js-yaml/package.json');
if (packageConfig.devDependencies['js-yaml'] !== yamlPackage.version) throw new Error('Install the pinned js-yaml dependency with npm ci first.');
let yamlReplacements = 0;
const result = await build({
  absWorkingDir: root,
  entryPoints: ['internal/admin/mermaid/renderer.js'],
  outfile: output,
  bundle: true,
  splitting: false,
  write: false,
  metafile: true,
  format: 'iife',
  platform: 'browser',
  target: ['es2020'],
  minify: true,
  charset: 'utf8',
  legalComments: 'external',
  plugins: [{
    name: 'patched-mermaid-yaml',
    setup(plugin) {
      plugin.onLoad({filter: /chunk-LNGE3PJU\.mjs$/}, args => {
        if (args.path !== yamlChunk) throw new Error('Unexpected Mermaid YAML chunk path.');
        yamlReplacements++;
        return {contents: "export { JSON_SCHEMA, load } from 'js-yaml';", loader: 'js', resolveDir: root};
      });
    },
  }],
  banner: {js: `/*! Mermaid ${mermaidPackage.version}; esbuild ${esbuildVersion}. Generated by scripts/build-mermaid.mjs. Third-party notices: webui-mermaid-LICENSE.txt */`},
});
if (yamlReplacements !== 1) throw new Error('The patched Mermaid YAML replacement was not applied exactly once.');
const generatedJS = result.outputFiles.find(file => file.path.endsWith('.js'));
const generatedLegal = result.outputFiles.find(file => file.path.endsWith('.LEGAL.txt'));
const outputMeta = result.metafile.outputs[output];
if (!generatedJS || !outputMeta || outputMeta.imports.length) throw new Error('The renderer must be a single self-contained classic script.');

const packages = new Map();
const prebundled = new Map();
for (const input of Object.keys(outputMeta.inputs).sort()) {
  if (!input.startsWith('node_modules/') || outputMeta.inputs[input].bytesInOutput === 0) continue;
  let directory = path.dirname(path.join(root, input));
  while (directory.startsWith(path.join(root, 'node_modules'))) {
    try {
      const metadata = JSON.parse(await readFile(path.join(directory, 'package.json'), 'utf8'));
      if (metadata.name && metadata.version) {
        packages.set(`${metadata.name}@${metadata.version}`, {metadata, directory});
        break;
      }
    } catch (error) {
      if (error.code !== 'ENOENT') throw error;
    }
    directory = path.dirname(directory);
  }
  // Mermaid publishes a few dependencies prebundled in its own chunks. Their
  // source maps retain the exact package/version; do not silently omit them.
  if (input.startsWith('node_modules/mermaid/') && path.join(root, input) !== yamlChunk) {
    try {
      const map = await json(`${input}.map`);
      for (const source of map.sources ?? []) {
        const embedded = source.match(/\.pnpm\/([^/]+)\/node_modules\/((?:@[^/]+\/)?[^/]+)/);
        if (embedded) {
          const name = embedded[2];
          const version = embedded[1].slice(embedded[1].lastIndexOf('@') + 1).split('_')[0];
          prebundled.set(`${name}@${version}`, {name, version});
        }
      }
    } catch (error) {
      if (error.code !== 'ENOENT') throw error;
    }
  }
}

const notices = new Map();
for (const [id, {metadata, directory}] of packages) {
  const files = (await readdir(directory)).filter(name => /^(license|licence|copying|notice)([.-].*)?$/i.test(name)).sort();
  if (!files.length) throw new Error(`Missing license text for bundled package ${id}`);
  const sections = [];
  for (const file of files) {
    const text = (await readFile(path.join(directory, file), 'utf8')).trim();
    sections.push(`${file}\n\n${text}`);
  }
  notices.set(id, `${id}\nLicense: ${metadata.license ?? 'See license text'}\n\n${sections.join('\n\n')}`);
}
for (const [id, {name, version}] of prebundled) {
  if (notices.has(id)) continue;
  const licenseFile = `internal/admin/mermaid/licenses/${name.replaceAll('/', '-')}-${version}.txt`;
  await access(path.join(root, licenseFile));
  const text = (await readFile(path.join(root, licenseFile), 'utf8')).trim();
  notices.set(id, `${id}\nPrebundled by Mermaid; license copied from the published npm package.\n\n${text}`);
}
const divider = '\n\n' + '='.repeat(78) + '\n\n';
const noticesText = `Mermaid diagram renderer — third-party license notices\n\nGenerated by scripts/build-mermaid.mjs from the actual bundled inputs and\nMermaid's published source maps. Versions are pinned by package-lock.json.\n\n${[...notices.entries()].sort(([a], [b]) => a.localeCompare(b, 'en')).map(([, text]) => text).join(divider)}${generatedLegal ? `${divider}Additional license comments retained by esbuild\n\n${generatedLegal.text.trim()}` : ''}\n`;
// npm's lockfile does not contain dependencies already compiled into Mermaid's
// published chunks. Include those exact source-map versions in advisory scans.
const inventory = [...notices.keys()].sort().map(id => {
  const split = id.lastIndexOf('@');
  return { name: id.slice(0, split), version: id.slice(split + 1), prebundled: !packages.has(id) };
});
const inventoryText = JSON.stringify({ schema: 1, mermaid: mermaidPackage.version, packages: inventory }, null, 2) + '\n';

for (const [file, contents] of [[output, generatedJS.contents], [noticeOutput, Buffer.from(noticesText)], [inventoryOutput, Buffer.from(inventoryText)]]) {
  const destination = path.join(root, file);
  if (check) {
    const existing = await readFile(destination);
    if (!existing.equals(Buffer.from(contents))) throw new Error(`${file} is out of date. Run npm run build:mermaid.`);
  } else {
    await writeFile(destination, contents);
  }
}
console.log(`Mermaid ${mermaidPackage.version}: ${generatedJS.contents.byteLength.toLocaleString('en')} bytes, ${notices.size} package notices; ${check ? 'verified' : 'built'}.`);
